/**
 * XML utility functions shared across all XML/SBML/SedML writers.
 */

/** Escape special XML characters in attribute values and text content. */
export function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}
